/**
 * Splits the blog out of the client bundle.
 *
 * src/blog/posts.ts holds every post's full text (~1 MB and growing with each
 * content-engine post). Importing it from client pages shipped all of it on
 * every page view. This script runs before tsc/vite and writes:
 *   - src/blog/index.generated.ts — metadata only (no content), for client pages
 *   - public/blog-data/<slug>.json — one post's body + FAQs, fetched on client-side
 *     navigation (first loads read the copy embedded by the prerender)
 * Both outputs are gitignored and rebuilt on every build/dev start.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const { blogPosts, postDivisions, getPostFaqs } = await import(
  pathToFileURL(path.join(root, 'src/blog/posts.ts')).href
);

interface Post { slug: string; title: string; metaDescription: string; date: string; author: string; keywords: string[]; content: string }

const index = (blogPosts as Post[]).map((p) => ({
  slug: p.slug,
  title: p.title,
  metaDescription: p.metaDescription,
  date: p.date,
  author: p.author,
  keywords: p.keywords,
  readMinutes: Math.max(1, Math.ceil(p.content.split(/\s+/).length / 230)),
  divisions: postDivisions[p.slug] ?? [],
}));

fs.writeFileSync(
  path.join(root, 'src/blog/index.generated.ts'),
  `// GENERATED by scripts/generate-blog-index.ts — do not edit.\nimport type { BlogPostMeta } from './meta';\n\nexport const blogIndex: BlogPostMeta[] = ${JSON.stringify(index, null, 1)};\n`,
);

const dataDir = path.join(root, 'public/blog-data');
fs.rmSync(dataDir, { recursive: true, force: true });
fs.mkdirSync(dataDir, { recursive: true });
for (const p of blogPosts as Post[]) {
  fs.writeFileSync(
    path.join(dataDir, `${p.slug}.json`),
    JSON.stringify({ slug: p.slug, content: p.content, faqs: getPostFaqs(p.slug) }),
  );
}
console.log(`✓ Blog index: ${index.length} posts`);
